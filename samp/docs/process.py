lines = markdown_content.split('\n')
current_offset = 0

out_lines = []
mapping = {} # old name -> new offset

for line in lines:
    if line.startswith('|') and not line.startswith('| ---') and not line.startswith('| **自动序号**'):
        parts = [p.strip() for p in line.split('|')]
        if len(parts) > 9:
            length = int(parts[5])
            old_addr_str = parts[2]
            name = parts[9].replace('<br>', '').replace(' ', '')
            
            # assign new addr
            if length == 1:
                new_addr_str = f"{current_offset:04X}"
            else:
                new_addr_str = f"{current_offset:04X}~{current_offset+length-1:04X}"
                
            new_4xxxx = 40001 + current_offset
            
            mapping[name] = current_offset
            
            # replace 自动序号 with sequential number or keep it? The prompt says "寄存器需要从40001开始编写"
            # Maybe the 自动序号 is just the offset+1?
            parts[1] = str(current_offset + 1)
            parts[2] = new_addr_str
            
            out_lines.append('|' + '|'.join(parts[1:-1]) + '|')
            current_offset += length
    else:
        out_lines.append(line)

print("\n".join(out_lines))
for k, v in mapping.items():
    print(f"{k}: {v:04X} ({40001+v})")
